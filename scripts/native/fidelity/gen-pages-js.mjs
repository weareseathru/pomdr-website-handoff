/**
 * Compiles per-page harvested inline scripts (pages-js/<slug>.js, written
 * by port.php) into native-pages.js: each page's code runs in its own
 * IIFE, gated on that page's .pg-<slug> stamp being present, so the file
 * is inert everywhere else. Enqueued in the footer for native pages.
 */
import fs from 'node:fs';
import path from 'node:path';
import { here } from './common.mjs';

const rawDir = path.join(here, 'pages-js');
const dest = path.resolve(here, '../../../divi-child-integration/assets/js/native-pages.js');
let out = `/* GENERATED by scripts/native/fidelity/gen-pages-js.mjs. Do not edit. */\n`;
if (fs.existsSync(rawDir)) {
  for (const f of fs.readdirSync(rawDir).filter((x) => x.endsWith('.js')).sort()) {
    const slug = f.replace(/\.js$/, '');
    out += `\n/* ---- page: ${slug} ---- */\nif (document.querySelector('.pg-${slug}')) { (function () {\n${fs.readFileSync(path.join(rawDir, f), 'utf8')}\n})(); }\n`;
  }
}
fs.writeFileSync(dest, out);
console.log(`native-pages.js: ${(out.length / 1024).toFixed(0)}KB`);
