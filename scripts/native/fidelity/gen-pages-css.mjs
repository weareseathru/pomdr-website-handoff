/**
 * Compiles per-page harvested styles (pages-css/<slug>.css, written by
 * port.php) into native-pages.css with every selector scoped under
 * .pg-<slug>, the class the porter stamps on that page's sections.
 * Unscoped harvesting once leaked one page's dark CTA band onto every
 * page including the reference standard; scoping makes that impossible.
 *
 * Run after any port: node gen-pages-css.mjs   (then gen-boost.mjs)
 */
import postcss from 'postcss';
import fs from 'node:fs';
import path from 'node:path';
import { here } from './common.mjs';

const rawDir = path.join(here, 'pages-css');
const dest = path.resolve(here, '../../../divi-child-integration/assets/css/native-pages.css');

let out = `/* GENERATED by scripts/native/fidelity/gen-pages-css.mjs. Do not edit.\n   Page-local template styles, scoped per page (.pg-<slug>). */\n`;

for (const file of fs.readdirSync(rawDir).filter((f) => f.endsWith('.css')).sort()) {
  const slug = file.replace(/\.css$/, '');
  const root = postcss.parse(fs.readFileSync(path.join(rawDir, file), 'utf8'));
  root.walkRules((rule) => {
    if (rule.parent && rule.parent.type === 'atrule' && /keyframes/i.test(rule.parent.name)) return;
    rule.selectors = rule.selectors.flatMap((sel) => {
      const t = sel.trim();
      // body prefix matches the boost layer so page rules outrank the
      // synthetic base and boosted shared rules, exactly as the reference
      // orders page-local styles after the shared stylesheets.
      const variants = [`body.pom-native .pg-${slug} ${t}`];
      // Section-level classes sit ON the same element as the pg stamp, so a
      // descendant prefix alone never matches; add the compound form.
      if (t.startsWith('.')) variants.push(`body.pom-native .pg-${slug}${t}`);
      return variants;
    });
  });
  out += `\n/* ---- page: ${slug} ---- */\n` + root.toString() + '\n';
}

fs.writeFileSync(dest, out);
console.log(`native-pages.css rebuilt, scoped: ${(out.length / 1024).toFixed(0)}KB`);
